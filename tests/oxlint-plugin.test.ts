import { RuleTester } from "oxlint/plugins-dev";
import { describe, it } from "vite-plus/test";

import { noRestatingComment, requireSuppressionReason } from "../src/oxlint-plugin.js";

RuleTester.describe = (text, fn) => {
  describe(text, () => {
    fn();
  });
};

RuleTester.it = it;

const tester = new RuleTester();

tester.run("require-suppression-reason", requireSuppressionReason, {
  invalid: [
    { code: "// eslint-disable-next-line no-console\nconsole.log(1);", errors: 1 },
    { code: "/* oxlint-disable */", errors: 1 },
    { code: "const a = 1; // eslint-disable-line no-unused-vars -- ok", errors: 1 },
  ],
  valid: [
    "// oxlint-disable-next-line no-console -- the CLI prints its report\nconsole.log(1);",
    "/* eslint-disable no-console -- generated file, regenerated by the build */",
    "// The disabled state comes from the API\nconst disabled = true;",
  ],
});

tester.run("no-restating-comment", noRestatingComment, {
  invalid: [
    { code: "// get the user\nconst user = getUser(id);", errors: 1 },
    { code: "/** Gets the user */\nconst user = getUser(id);", errors: 1 },
    { code: "const total = count + 1; // total count", errors: 1 },
    { code: "// return the result\nreturn result;", errors: 1 },
  ],
  valid: [
    "// Retry once: the first call warms the remote cache\nconst user = getUser(id);",
    "// get the user\n// then the account\nconst user = getUser(id);",
    "/** @returns the user */\nconst user = getUser(id);",
    "// @ts-expect-error: the fixture is deliberately untyped\nconst user = getUser(id);",
  ],
});
